using System;
using SQLite;

namespace Recall.Windows.Models;

/// <summary>
/// Represents an indexed document, image, screenshot, or note stored in Recall.
/// </summary>
[Table("IndexedItems")]
public class IndexedItem
{
    [PrimaryKey]
    public string Id { get; set; } = Guid.NewGuid().ToString();

    [Indexed]
    public string Path { get; set; } = string.Empty;

    public string Name { get; set; } = string.Empty;

    public string Kind { get; set; } = string.Empty; // "PNG", "JPEG", "PDF", "MD"

    public string ContentType { get; set; } = "Image"; // "Image", "Article", "Note", "PDF"

    public DateTime ModifiedAt { get; set; } = DateTime.UtcNow;

    public DateTime AddedAt { get; set; } = DateTime.UtcNow;

    public long ByteSize { get; set; }

    /// <summary>
    /// Combined searchable extracted text from OCR, PDF parser, or Markdown.
    /// </summary>
    public string SearchableText { get; set; } = string.Empty;

    /// <summary>
    /// Automatic captions/tags generated by vision models.
    /// </summary>
    public string? AiCaption { get; set; }

    public string? AiTags { get; set; } // Comma-separated tags

    public string? DominantColorHex { get; set; } // e.g. "#E63946"

    public string? DominantColorName { get; set; } // "red", "blue", "dark", "white"

    public bool IsFavorite { get; set; }

    public string? UserNote { get; set; }

    public string? SourceUrl { get; set; }

    public string? SourceSite { get; set; }

    public string? DetectedPrice { get; set; }

    /// <summary>
    /// Serialized float vector embedding (MobileCLIP / sentence-transformer).
    /// </summary>
    public byte[]? EmbeddingBytes { get; set; }

    [Ignore]
    public float[]? Embedding
    {
        get
        {
            if (EmbeddingBytes == null || EmbeddingBytes.Length == 0) return null;
            var floats = new float[EmbeddingBytes.Length / sizeof(float)];
            Buffer.BlockCopy(EmbeddingBytes, 0, floats, 0, EmbeddingBytes.Length);
            return floats;
        }
        set
        {
            if (value == null)
            {
                EmbeddingBytes = null;
                return;
            }
            EmbeddingBytes = new byte[value.Length * sizeof(float)];
            Buffer.BlockCopy(value, 0, EmbeddingBytes, 0, EmbeddingBytes.Length);
        }
    }
}
